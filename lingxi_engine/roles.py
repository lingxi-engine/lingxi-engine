#
# 系统指令要求：
#   在 orchestrator.py、roles.py 中定义角色集合（质疑者、建设者、总结者），
#   为每个模型分配角色，并在构造提示词时注入角色对应的系统指令；
#   同时更新 prompts 相关文件，使不同角色按职责发言，形成观点碰撞。

