# 角色分配顺序：模型名按注册顺序轮流分配，保证每个角色都有模型承担
ROLE_SEQUENCE = ['质疑者', '建设者', '总结者']

# 明确的分歧信号词：一旦发言中出现，说明讨论尚未收敛。
# 注意：这些词会被否定语境豁免（见 _NEGATION_TAIL_RE），避免
# "我不存在分歧的看法"这类否定表述被误判为存在分歧。
DIVERGENCE_KEYWORDS = (
    '反对', '不同意', '有异议', '不认可',
    '我反对', '不同意这个', '有分歧', '存在分歧',
    'disagree', 'objection',
)

# 否定豁免正则：检查关键词【紧邻前方】是否为否定语境（锚定到关键词起点）。
#
# 旧实现（前窗启发式）有两个漏洞：
#   1) 否定词与关键词共享字符时豁免失效——"不存在分歧"里否定词"不存在"
#      与关键词"存在分歧"重叠，重叠部分永远进不了关键词前方窗口，
#      导致该句仍被判为分歧；
#   2) 窗口过宽时远处否定词误伤——"毫无根据的存在分歧"因 6 字符窗口
#      内出现"无"而被错误豁免。
#
# 新实现：否定词必须紧邻关键词（中间最多隔一个助词"的/地"），
# 用 endpos 锚定的正则匹配，天然规避字符重叠与远距误伤。
# 注意："不存在"必须排在单字否定之前——"目前不存在反对的声音"里，
# 紧邻关键词"反对"的是"在"，只有完整的"不存在"单元才能命中豁免。
# 英文否定（don't/isn't）暂不支持，属已知限制。
_NEGATION_TAIL_RE = re.compile(
    r'(?:并非|不是|没有|毫无|不存在|不|无|非)(?:的|地)?$')


def assign_roles(model_names):
    """为模型列表分配角色。

    按注册顺序轮流分配质询者/建设者/总结者，保证角色均衡。
    返回 {model_name: role_name} 的映射。
    """
    if not model_names:
        return {}
    assignment = {}
    for i, name in enumerate(model_names):
        role = ROLE_SEQUENCE[i % len(ROLE_SEQUENCE)]
        assignment[name] = role
    return assignment


def get_role_instruction(role_name):
    """返回指定角色的完整系统指令（含角色规则）。"""
    role = ROLES.get(role_name)
    if not role:
        # 未知名角色回退为通用协作指令
        return (
            '你扮演【通用协作】角色。\n'
            '请仔细阅读其他模型的发言，基于已有讨论推进，避免重复，达成共识时明确表达。\n'
        )
    return role['rules']


def get_role_description(role_name):
    """返回角色的简短描述。"""
    role = ROLES.get(role_name)
    return role['description'] if role else '通用协作角色'


def get_all_roles():
    """返回全部角色名列表。"""
    return list(ROLES.keys())


def has_divergence(texts):
    """检测一组发言中是否存在明确的分歧信号。

    若任一发言出现"反对/不同意/有异议"等信号，说明讨论尚未收敛，
    用于收敛检测时避免把"句式相似但观点相反"误判为达成共识。

    否定豁免："我不存在分歧"、"没有反对意见"、"并非不同意"这类否定/
    澄清表述不算分歧。实现上对每处关键词命中，检查其紧邻前方是否为
    否定词（最多隔一个助词），命中则跳过该处继续向后找。
    """
    for text in texts or []:
        if not text:
            continue
        for kw in DIVERGENCE_KEYWORDS:
            start = 0
            while True:
                idx = text.find(kw, start)
                if idx == -1:
                    break
                # 关键词紧邻前方是否定语境 -> 豁免该处，继续向后找
                if _NEGATION_TAIL_RE.search(text, 0, idx):
                    start = idx + len(kw)
                    continue
                return True
    return False
