SITE_DIR="/opt/lingxi-site"
LOG="/var/log/lingxi-deploy.log"

log() { echo "[$(date '+%H:%M:%S')] $*" | tee -a "$LOG"; }

log "===== LingXi site installer START ====="

if [ "$(id -u)" -ne 0 ]; then log "FATAL: not root"; exit 1; fi
log "OK: root"

# ---------- 1. open host firewall ----------
log ""
log ">>> [1/6] opening 22/80/443 on the host"
export DEBIAN_FRONTEND=noninteractive
if command -v ufw >/dev/null 2>&1; then
  ufw allow 22/tcp  >/dev/null 2>&1
  ufw allow 80/tcp  >/dev/null 2>&1
  ufw allow 443/tcp >/dev/null 2>&1
  ufw --force enable >/dev/null 2>&1
  log "  ufw: $(ufw status | head -1)"
else
  log "  ufw: not installed (fine on Ubuntu 24.04)"
fi
if command -v iptables >/dev/null 2>&1; then
  for p in 22 80 443; do
    iptables -I INPUT -p tcp --dport $p -j ACCEPT 2>/dev/null
  done
  iptables -P INPUT ACCEPT 2>/dev/null
  log "  iptables INPUT: $(iptables -S INPUT 2>/dev/null | head -1)"
fi
if ! systemctl is-active --quiet ssh; then
  log "  ssh inactive, restarting"
  systemctl restart ssh 2>/dev/null
fi
log "  ssh: $(systemctl is-active ssh 2>/dev/null)"

# ---------- 2. install nginx + certbot ----------
log ""
log ">>> [2/6] installing nginx / certbot / curl"
NEED=""
for c in nginx certbot curl; do
  command -v "$c" >/dev/null 2>&1 || NEED="$NEED $c"
done
if [ -n "$NEED" ]; then
  apt-get update -qq 2>&1 | tail -2 | sed 's/^/     /'
  apt-get install -y -qq $NEED 2>&1 | tail -4 | sed 's/^/     /'
fi
systemctl enable --now nginx >/dev/null 2>&1
log "  nginx: $(systemctl is-active nginx 2>/dev/null)"

NGINX_VER_OK=$(nginx -v 2>&1 | sed -n 's|.*nginx/\([0-9][0-9]*\.[0-9][0-9]*\).*|\1|p')
NGINX_MAJOR=${NGINX_VER%%.*}
NGINX_MINOR=${NGINX_VER#*.}
NGINX_MINOR=${NGINX_MINOR%%.*}
if [ -n "$NGINX_VER" ] && [ "$NGINX_MAJOR" -gt 1 ]; then
  SUPPORTS_HTTP2_DIRECTIVE=1
elif [ "$NGINX_MAJOR" -eq 1 ] && [ "$NGINX_MINOR" -ge 25 ]; then
  SUPPORTS_HTTP2_DIRECTIVE=1
else
  SUPPORTS_HTTP2_DIRECTIVE=0
fi
log "  nginx version: ${NGINX_VER:-unknown} (http2-directive=${SUPPORTS_HTTP2_DIRECTIVE})"

