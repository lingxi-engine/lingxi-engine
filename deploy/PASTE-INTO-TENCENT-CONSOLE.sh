#    (web terminal). Upload this file OR paste its contents, then:
#        bash PASTE-INTO-TENCENT-CONSOLE.sh
#
#  WHY: ports 22/80/443 are unreachable from the public internet,
#  but the VM itself is healthy (sshd active, listening on 0.0.0.0:22,
#  inbound sessions present in sshd logs). The block is at the cloud
#  firewall layer. This installer opens the ports locally AND deploys
#  the site, so once the cloud firewall allows 80/443 the site is live.
