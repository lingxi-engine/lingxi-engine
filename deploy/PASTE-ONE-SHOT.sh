#!/usr/bin/env bash
# ============================================================
#  灵犀官网 一键部署（站点包已内联 · 无需上传任何文件）
#  用法: 腾讯云控制台 -> 登录(网页终端) -> 粘贴本脚本全文 -> 回车
#  幂等: 可重复执行，已完成的步骤会跳过
#  注意: 需要 root（腾讯云默认就是 root）
# ============================================================
set -uo pipefail

DOMAIN="lingxi-engine.com"
SITE_DIR="/opt/lingxi-site"
LOG="/var/log/lingxi-deploy.log"

log() { echo "[$(date '+%H:%M:%S')] $*" | tee -a "$LOG"; }

log "===== 灵犀官网部署开始 ====="
log "域名: $DOMAIN"
log "目录: $SITE_DIR"

if [ "$(id -u)" -ne 0 ]; then
  log "需要 root 权限"
  exit 1
fi

# ---------- 1. 端口预检（绝不覆盖已有服务）----------
log ""
log ">>> [1/9] 端口占用预检"
BUSY=""
for p in 80 443; do
  if ss -tlnp 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${p}$"; then
    BUSY="$BUSY $p"
  fi
done
if [ -n "$BUSY" ]; then
  log "端口被占用: $BUSY"
  ss -tlnp 2>/dev/null | grep -E "[:.](80|443)$" | sed 's/^/     /'
  exit 2
fi
log "80/443 空闲"

# ---------- 2. 备份已有配置 ----------
log ""
log ">>> [2/9] 备份现有配置"
mkdir -p /root/lingxi-backup
STAMP=$(date '+%Y%m%d_%H%M%S')
if [ -d /etc/nginx/conf.d ]; then
  tar -czf "/root/lingxi-backup/nginx-conf-${STAMP}.tar.gz" /etc/nginx/conf.d 2>/dev/null && log "已备份 nginx 配置"
fi
iptables-save > "/root/lingxi-backup/iptables-${STAMP}.rules" 2>/dev/null && log "已备份 iptables 规则"

# ---------- 3. 安装组件 ----------
log ""
log ">>> [3/9] 安装 nginx / certbot / curl"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq >/dev/null 2>&1
NEED=""
for c in nginx certbot curl; do
  command -v "$c" >/dev/null 2>&1 || NEED="$NEED $c"
done
if [ -n "$NEED" ]; then
  apt-get install -y -qq $NEED >/dev/null 2>&1 && log "安装完成: $NEED"
else
  log "已全部安装，跳过"
fi
systemctl enable --now nginx >/dev/null 2>&1
log "nginx 状态: $(systemctl is-active nginx)"

