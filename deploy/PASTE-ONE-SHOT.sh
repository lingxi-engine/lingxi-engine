# ---------- 7. 申请 HTTPS 证书 ----------
log ""
log ">>> [7/9] 申请 Let's Encrypt 证书"
mkdir -p /var/www/html/.well-known/acme-challenge
if certbot certonly --webroot -w /var/www/html \
     -d "$DOMAIN" -d "www.$DOMAIN" \
     --non-interactive --agree-tos \
     --register-unsafely-without-email \
     --keep-until-expiring >/dev/null 2>&1; then
  log "证书签发成功"
else
  log "证书签发失败（不影响 HTTP 访问，稍后可重跑本脚本补证书）"
fi

# ---------- 8. 启用 443 + 强制跳转 ----------
log ""
log ">>> [8/9] 启用 HTTPS"
if [ -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ]; then
  cat > /etc/nginx/conf.d/lingxi-site.conf <<'NGINXEOF'
server {
    listen 80;
    listen [::]:80;
    server_name lingxi-engine.com www.lingxi-engine.com;
    location ^~ /.well-known/acme-challenge/ { root /var/www/html; default_type "text/plain"; allow all; }
    location / { return 301 https://$host$request_uri; }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name lingxi-engine.com www.lingxi-engine.com;

    ssl_certificate     /etc/letsencrypt/live/lingxi-engine.com/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/lingxi-engine.com/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 14400m;

    add_header Strict-Transport-Security "max-age=31536000" always;

    location / {
        root /opt/lingxi-site;
        index index.html;
        try_files $uri $uri/ /index.html;
    }

    location ~* \.(css|js|svg|png|jpg|webp|woff2?)$ {
        root /opt/lingxi-site;
        expires 7d;
        add_header Cache-Control "public, max-age=604800";
    }

    access_log /var/log/nginx/lingxi-access.log;
    error_log  /var/log/nginx/lingxi-error.log;
}
NGINXEOF
  if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx 2>/dev/null || systemctl restart nginx
    log "HTTPS 已启用，HTTP 自动 301 跳转"
    curl -s -o /dev/null -w "  HTTPS 本机自检 %{http_code}\n" --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/"
  else
    log "443 配置有错，保留 HTTP"
  fi
